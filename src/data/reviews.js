/**
 * Returns up to maxLimit authentic reviews (enforces the max 20 cap)
 */
export function getReviews(limit = 20) {
  const cap = Math.min(limit, 20);
  return AUTHENTIC_REVIEWS.slice(0, cap);
}

/**
 * Returns the 5-6 featured reviews for the Homepage section
 */
export function getHomepageFeaturedReviews(count = 6) {
  const featured = AUTHENTIC_REVIEWS.filter((r) => r.featured);
  if (featured.length >= count) {
    return featured.slice(0, count);
  }
  const remaining = AUTHENTIC_REVIEWS.filter((r) => !r.featured);
  return [...featured, ...remaining].slice(0, count);
}
